        "def search_score(scores):\n",
        "    \"\"\"Searches for a specific score in the list.\"\"\"\n",
        "    try:\n",
        "        target = float(input(\"\\nEnter the score to search for: \"))\n",
        "        found_indices = []\n",
        "\n",
        "        for index, score in enumerate(scores):\n",
        "            if score == target:\n",
        "                found_indices.append(index)\n",
        "\n",
        "        if found_indices:\n",
        "            print(f\"Score {target} found at index position(s): {found_indices}\")\n",
        "        else:\n",
        "            print(f\"Score {target} was not found in the list.\")\n",
        "    except ValueError:\n",
        "        print(\"Invalid input! Please enter a numeric value.\")\n",
        "\n",
        "\n",
        "def compute_average(scores):\n",
        "    \"\"\"Computes and displays the average, highest, and lowest scores.\"\"\"\n",
        "    if not scores:\n",
        "        print(\"\\nCannot compute average. The list is empty.\")\n",
        "        return\n",
        "    total = sum(scores)\n",
        "    average = total / len(scores)\n",
        "    print(\"\\n--- Score Summary ---\")\n",
        "    print(f\"Total Students : {len(scores)}\")\n",
        "    print(f\"Average Score  : {average:.2f}\")\n",
        "    print(f\"Highest Score  : {max(scores)}\")\n",
