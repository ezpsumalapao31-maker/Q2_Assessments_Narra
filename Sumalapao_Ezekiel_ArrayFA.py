        "def display_scores(scores, title=\"Current Student Scores\"):\n",
        "    \"\"\"Displays array/list elements with their index numbers.\"\"\"\n",
        "    print(f\"\\n--- {title} ---\")\n",
        "    if not scores:\n",
        "        print(\"No scores available.\")\n",
        "        return\n",
        "    for index, score in enumerate(scores):\n",
        "        print(f\"Index [{index}] : {score}\")\n",
